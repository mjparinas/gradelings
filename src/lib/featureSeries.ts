// The feature series: one email a day after a parent signs up and confirms their email, each about one thing the
// app does, with a real screenshot (owner request, November 26, 2026; docs/decisions/2026-11-26-daily-feature-emails.md).
// This file is the order they go out in and the words. It is pure, so tests and the admin panel can read it.
//
// Rules for what goes in here:
// - Only what the app really does today. A feature behind a flag that is off carries `flag`, and waits for it.
// - `tier` says who has it: "free" for everyone, "plan" for the Family plan only (included in the free trial),
//   "both" when part of it is free and part needs the plan. Plan parts are always named as such, never hidden.
// - Never type the trial length, prices or limits: they come from plan.ts (see `fill`).
// - No promises about marks or grades, no health claims (calm mode is about presentation), no "certified".
// - Words say "Pre-K to Grade 9". Canadian spelling (US families are localized when the email is built).

export type Tier = "free" | "plan" | "both";
/** Who the email is for: everyone, or only families with a child in these age bands (little: Pre-K to 1, middle 2 to 4, big 5 to 9). */
export type Ages = "little" | "middle" | "big";

export interface ShotSpec {
  /** Which app the screen is in. */
  app: "play" | "parents";
  /** The hash route to open (the screenshot script sets up a demo child with a few weeks of practice first). */
  hash: string;
  /** A phone for the kids' app and its look on a small screen, a wide window for parent screens. */
  device: "phone" | "desktop";
  /** Which demo child: a Pre-K to Grade 1 child sees the little-kids version of the app. */
  child?: "little" | "big";
  /** A button to press once the screen is open (a tab in Reports, a page in the Sticker Book). */
  click?: string;
  /** Text to scroll to the top of the screen first, for a card lower down. */
  scrollTo?: string;
}

export interface FeatureEmail {
  /** Never rename or remove an id once it has been sent: it is the family's record of having had it. */
  id: string;
  tier: Tier;
  subject: string;
  /** The text mail clients show beside the subject. */
  preheader: string;
  title: string;
  /** One or two sentences under the title. */
  intro: string;
  /** Three or four short points. */
  points: string[];
  /** The coloured "Did you know?" callout. */
  dyk: string;
  button: { label: string; path: string };
  shot: ShotSpec;
  /** Waits until this flag is on for the family. */
  flag?: FlagKey;
  /** Only for families with a child in these age bands. */
  ages?: Ages[];
  /** Only for families in these countries (French is taught in Canada only). */
  countries?: CountryCode[];
  /** What the screenshot shows, for screen readers. */
  alt: string;
}

const play = (hash: string, device: ShotSpec["device"] = "phone", child?: ShotSpec["child"], more: Pick<ShotSpec, "click" | "scrollTo"> = {}): ShotSpec => ({ app: "play", hash, device, child, ...more });
const parents = (hash: string, click?: string, scrollTo?: string): ShotSpec => ({ app: "parents", hash, device: "desktop", click, scrollTo });

