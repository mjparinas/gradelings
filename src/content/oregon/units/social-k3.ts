/** "Which county is on the coast?" or "Which county is east of the Cascades?" */
function coastOrEast(): Question {
  if (chance(0.5)) {
    return textChoice(
      "Which county is on the Oregon coast?",
      pick(COASTAL),
      sample(EASTERN, 2),
      "Clatsop, Tillamook, Lincoln, Coos and Curry Counties all touch the Pacific Ocean.",
    );
  }
  const east = pick(EASTERN);
  return textChoice("Which county is east of the Cascade Range?", east, sample(COASTAL, 2), `${east} is in eastern Oregon, east of the Cascades.`);
}

const countySeats = (n: number) =>
  factQuestions(COUNTY_SEATS, n, {
    ask: (county) => `What is the county seat of ${county}?`,
    reverse: (seat) => `${seat} is the county seat of which county?`,
    hint: (county, seat) => `${seat} is the county seat of ${county}.`,
  });

