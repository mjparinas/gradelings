"""Writes src/content/prince-edward-island/overall.ts (the learning focus parents see on a course page) from outcomes.json.
Usage: python3 -I build_overall.py outcomes.json ../../../src/content/prince-edward-island/overall.ts
"""
import json, re, sys

d = json.load(open(sys.argv[1], encoding="utf8"))

def first_sentence(t, n=300):
    t = re.sub(r"\s*\(Intermediate Program of Studies\)\s*$", "", t.strip())
    t = re.split(r"(?<=[.])\s", t)[0]
    t = t.split(" by:")[0].rstrip(":;,")
    if len(t) > n:
        t = t[:n].rsplit(" ", 1)[0] + "…"
    return t if t.endswith("…") else t.rstrip(".") + "."

def lines_for(key, rows):
    sub = key.split("/")[1]
    grade = key.split("/")[0]
    out = []
    placeholder = lambda r: "not in the repository" in r["text"] or r["text"].startswith("Unit named in the PEI")
    if sub == "math":
        seen = []
        for r in rows:
            g = r["group"] or r["code"]
            if g in seen:
                continue
            seen.append(g)
            out.append(f"{g}." if placeholder(r) else f"{g}. {first_sentence(r['text'])}")
    elif sub == "language":
        for r in rows:
            if r["code"].startswith("GCO"):
                out.append(f"{r['group']}. {first_sentence(r['text'])}")
    elif sub == "science":
        for r in rows:
            if r["code"].startswith("GCO"):
                continue
            out.append(f"{r['code']}.")
        if not out:
            out = [f"{r['code']}." for r in rows]
    elif sub == "social":
        gco = [r for r in rows if r["code"].startswith("GCO")]
        if gco:
            for r in gco:
                out.append(f"{r['group']}. {first_sentence(r['text'])}")
        else:
            seen = []
            for r in rows:
                g = r["group"] or r["code"]
                if g in seen:
                    continue
                seen.append(g)
                out.append(f"{g}. {first_sentence(r['text'])}" if r["group"] else f"{r['code']}. {first_sentence(r['text'])}")
    elif sub == "core-french":
        gco = [r for r in rows if r["code"].startswith("GCO")]
        for r in gco:
            out.append(f"{r['group']}. {first_sentence(r['text'])}")
        if not out:
            out = ["Core French. The Grades 7 to 9 program builds confidence in learning and using French through purposeful, action-oriented tasks set in authentic contexts."]
    return out

lines = [
    "// Generated by docs/research/prince-edward-island/build_overall.py from outcomes.json. Do not edit by hand.",
    "// Each list is what a course page shows parents as its learning focus.",
    "",
    "export const OVERALL: Record<string, string[]> = {",
]
for key, rows in d.items():
    ls = lines_for(key, rows)
    if not ls:
        continue
    lines.append(f"  {json.dumps(key)}: [")
    for l in ls:
        lines.append("    " + json.dumps(l, ensure_ascii=False) + ",")
    lines.append("  ],")
lines += [
    "};",
    "",
    "/** The learning focus for one course; throws when a course has none, so a missing one fails loudly. */",
    "export function overall(grade: string, subject: string): string[] {",
    "  const list = OVERALL[`${grade}/${subject}`];",
    "  if (!list?.length) throw new Error(`No Prince Edward Island learning focus for ${grade}/${subject}`);",
    "  return list;",
    "}",
    "",
]
open(sys.argv[2], "w", encoding="utf8").write("\n".join(lines))
